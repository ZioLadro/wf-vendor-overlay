STRINGS = {"en": EN, "it": IT}


_LANG = STRINGS.get(CFG.get("language", "en"), EN)    # fixed at startup: changing it needs a restart


def t(key: str, /, **kw) -> str:   # positional-only: placeholders may be called "key"
    lang = _LANG
    s = lang.get(key)
    if s is None:
        s = EN.get(key, key)
    return s.format(**kw) if kw else s
