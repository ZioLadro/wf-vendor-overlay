"""Which items each vendor sells.

- vendors.json (bundled): vendors and syndicates, generated by build_vendors.py from the game data.
  If %LOCALAPPDATA%\\WFVendorOverlay\\vendors.json exists it takes precedence (to update/edit it).
- Baro Ki'Teer: not in the game data (his inventory changes at every visit). His historical list is
  read from the wiki (Module:Baro/data) and, when he is present, from his current inventory (warframestat).
  The result is saved in baro.json and refreshes itself every `baro_refresh_days` days.
Names are matched to warframe.market items: only tradable ones appear in the price list.
"""
import json
import re
import sys
import time
from pathlib import Path

import requests

from config import APP_DIR, CFG
from i18n import t
from matcher import norm

BUNDLED = Path(getattr(sys, "_MEIPASS", Path(__file__).resolve().parent)) / "vendors.json"
USER_FILE = APP_DIR / "vendors.json"
BARO_FILE = APP_DIR / "baro.json"
BARO = "Baro Ki'Teer"
WIKI_URLS = (
    "https://wiki.warframe.com/w/Module:Baro/data?action=raw",
    "https://wiki.warframe.com/index.php?title=Module:Baro/data&action=raw",
)
API_URL = "https://api.warframestat.us/pc/voidTrader"
UA = "WFVendorOverlay/1.3 (overlay personale; richieste rare)"
_STR = re.compile(r'"((?:[^"\\\n]|\\.)*)"|\'((?:[^\'\\\n]|\\.)*)\'')


def _read(path: Path):
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else None
    except Exception:
        return None


def lua_strings(text: str) -> list:
    """All the quoted strings of a Lua source (ignores comment lines)."""
    text = re.sub(r"--\[(=*)\[.*?\]\1\]", "", text, flags=re.S)          # block comments
    out = []
    for line in text.splitlines():
        if line.lstrip().startswith("--"):
            continue
        for m in _STR.finditer(line):
            s = m.group(1) if m.group(1) is not None else m.group(2)
            out.append(s.replace("\\'", "'").replace('\\"', '"').replace("\\\\", "\\"))
    return out


def fetch_baro(name_slug: dict, timeout: float = 25.0):
    """Downloads Baro's items. Returns ({norm: name}, info, errors); only names present on the market."""
    names, info, errors = {}, {}, []
    for url in WIKI_URLS:                                   # full history (wiki)
        try:
            r = requests.get(url, headers={"User-Agent": UA}, timeout=timeout)
            r.raise_for_status()
            found = {norm(s): s for s in lua_strings(r.text) if norm(s) in name_slug}
            if found:
                names.update(found)
                info["wiki"] = len(found)
                break
            errors.append("wiki: response without recognisable items")
        except Exception as e:
            errors.append(f"wiki: {type(e).__name__}")
    try:                                                    # current inventory (when Baro is present)
        r = requests.get(API_URL, headers={"User-Agent": UA}, timeout=timeout)
        r.raise_for_status()
        cur = 0
        for it in (r.json().get("inventory") or []):
            n = it.get("item") or it.get("name") or ""
            if norm(n) in name_slug:
                names.setdefault(norm(n), n)
                cur += 1
        info["ora"] = cur
    except Exception as e:
        errors.append(f"worldstate: {type(e).__name__}")
    return names, info, errors


class VendorIndex:
    def __init__(self, name_slug: dict):
        self.name_slug = name_slug              # {normalised name: slug} from the market catalog
        self.by_slug = {}                       # slug -> [vendor, ...]
        self.standing = {}                      # slug -> [{"v": vendor, "s": standing cost, "r": required rank}]
        self.vendor_names = []
        self.rebuild()

    def rebuild(self):
        static = _read(USER_FILE) or _read(BUNDLED) or {}
        vendors = dict(static.get("vendors") or {})
        baro = (_read(BARO_FILE) or {}).get("names") or []
        if baro:
            vendors[BARO] = baro
        by_slug, standing = {}, {}
        for vname, entries in vendors.items():
            for e in entries:
                cost = rank = tag = None
                if isinstance(e, dict):                             # {"n": name | [blueprint, base], "s": standing, "r": rank}
                    cost, rank, tag, e = e.get("s"), e.get("r"), e.get("t"), e.get("n")
                for cand in ([e] if isinstance(e, str) else e):     # [blueprint name, base name]: the first that exists
                    slug = self.name_slug.get(norm(cand))
                    if slug:
                        by_slug.setdefault(slug, set()).add(vname)
                        if cost:
                            standing.setdefault(slug, []).append({"v": vname, "s": cost, "r": rank or 0, "t": tag})
                        break
        self.by_slug = {s: sorted(v) for s, v in by_slug.items()}
        self.standing = {s: sorted(v, key=lambda x: (x["s"], x["v"])) for s, v in standing.items()}
        self.vendor_names = sorted({v for vs in self.by_slug.values() for v in vs})

    # ---------- Baro ----------
    def baro_age(self):
        """Seconds since Baro's list was last updated (None if never)."""
        u = (_read(BARO_FILE) or {}).get("updated")
        return time.time() - u if u else None

    def baro_is_stale(self) -> bool:
        age = self.baro_age()
        return age is None or age > float(CFG["baro_refresh_days"]) * 86400

    def refresh_baro(self):
        """Updates Baro's list from the internet. Returns (ok, message)."""
        names, info, errors = fetch_baro(self.name_slug)
        if not names:
            return False, t("baro.nodata", err="; ".join(errors) or t("baro.emptylist"))
        old = (_read(BARO_FILE) or {}).get("names") or []
        merged = {norm(n): n for n in old}                     # the history is never lost
        merged.update(names)
        try:
            BARO_FILE.write_text(json.dumps({"updated": int(time.time()), "info": info,
                                             "names": sorted(merged.values())}, ensure_ascii=False),
                                 encoding="utf-8")
        except OSError as e:
            return False, t("baro.savefail", err=e)
        self.rebuild()
        n = len(self.by_slug_for(BARO))
        msg = t("baro.updated", n=n)
        if errors:
            msg += t("baro.partial", err="; ".join(errors))
        return True, msg

    # ---------- vendor name on screen ----------
    _GENERIC = {"pet", "event", "hub", "tau", "duviri", "cetus", "fortuna", "deimos", "zariman", "focus", "tau",
                "game modes", "1999", "ascension", "conservation rewards"}

    def _aliases(self):
        """{normalised text that can head that vendor's screen: {vendors}} — the vendor's name, without a leading
        'The', without the '(…)' note and, for 'Place · Name', the Name part."""
        if getattr(self, "_alias_map", None) is None:
            from matcher import norm
            amap = {}
            for v in self.vendor_names:
                cands = {v}
                if "·" in v:
                    cands.add(v.split("·", 1)[1])
                for c in list(cands):
                    cands.add(re.sub(r"\s*\(.*?\)", "", c))
                for c in list(cands):
                    cands.add(re.sub(r"^\s*the\s+", "", c, flags=re.I))
                for c in cands:
                    n = norm(c)
                    if len(n) >= 5 and n not in self._GENERIC:
                        amap.setdefault(n, set()).add(v)
            self._alias_map = amap
        return self._alias_map

    def header_vendors(self, texts, cutoff=88):
        """Vendors whose name appears as a line of the text read on screen. texts: [(text, x, y, w, h)]."""
        from matcher import norm
        from rapidfuzz import fuzz, process
        amap = self._aliases()
        keys, found = list(amap), set()
        for tx in texts:
            n = norm(tx[0])
            if len(n) < 5:
                continue
            if n in amap:
                found |= amap[n]
                continue
            r = process.extractOne(n, keys, scorer=fuzz.ratio, score_cutoff=cutoff)
            if r:
                found |= amap[r[0]]
        return found

    def identify(self, slugs, min_items=3, min_share=0.6, header=()):
        """Which vendor's screen is it? The vendor whose stock covers most of the items the OCR matched.
        Returns (vendor, indices of the slugs that belong to it), or (None, []) when no vendor covers enough of
        them (e.g. an inventory or chat window that just happens to show some item names)."""
        count = {}
        for s in slugs:
            for v in self.by_slug.get(s, ()):
                count[v] = count.get(v, 0) + 1
        if not count or not slugs:
            return None, []
        if not hasattr(self, "_sizes") or self._sizes[0] is not self.by_slug:
            sizes = {}
            for vs in self.by_slug.values():
                for v in vs:
                    sizes[v] = sizes.get(v, 0) + 1
            self._sizes = (self.by_slug, sizes)
        # most covered; on a tie the vendor with the smaller stock (more specific)
        pick = lambda pool: max(pool, key=lambda v: (count[v], -self._sizes[1].get(v, 0)))
        named = [v for v in header if v in count]
        if named:                       # the name is on screen and some of the items are its own: enough
            best = pick(named)
            return best, [i for i, s in enumerate(slugs) if best in self.by_slug.get(s, ())]
        best = pick(count)
        if count[best] < min_items or count[best] / len(slugs) < min_share:
            return None, []
        return best, [i for i, s in enumerate(slugs) if best in self.by_slug.get(s, ())]

    def by_slug_for(self, vendor: str) -> list:
        return [s for s, vs in self.by_slug.items() if vendor in vs]
